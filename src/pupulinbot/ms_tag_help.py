PENDING_RARITY = frozenset({"吃瓜群众", "一鸣惊人", "鏖战"})


def tag_help(query: str) -> str:
    tag = query.strip().lstrip("#＃").strip()
    if not tag:
        return "用法：taghelp <标签名称>，例如 taghelp 进退自如。"
    description = TAG_DESCRIPTIONS.get(tag)
    if description is None:
        wins, victims = yakuman_tag_groups()
        if tag in wins:
            description = f"本次查询中和过「{tag}」，并有具体役名记录。"
        elif tag in victims:
            yaku = "国士无双" if tag == "国士受害者" else tag.removesuffix("受害者")
            description = f"本次查询中放铳给「{yaku}」，或坐庄时被该役满自摸。"
        else:
            return "未找到这个成就，请输入 msstyle 卡片上显示的标签名。"
    lines = [f"【{tag}】", description]
    if tag in PENDING_RARITY:
        lines.append("稀有度待核验，暂以灰色显示，不代表常见。")
    return "\n".join(lines)
